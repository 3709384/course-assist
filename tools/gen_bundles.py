#!/usr/bin/env python3
"""Generate src/CourseAssist.Core/BundlesData.cs from bundles/*.yaml.

The YAML texts are compiled into the Core library as string constants, so the
shipped executable always carries every course bundle inside itself — no loose
files to lose, no folders to go stale. Run after editing anything in bundles/:

    python3 tools/gen_bundles.py
"""
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLES_DIR = os.path.join(ROOT, "bundles")
OUT = os.path.join(ROOT, "src", "CourseAssist.Core", "BundlesData.cs")


def main() -> int:
    files = sorted(glob.glob(os.path.join(BUNDLES_DIR, "*.yaml")))
    if not files:
        print("no bundles found", file=sys.stderr)
        return 1

    lines = [
        "// <auto-generated> by tools/gen_bundles.py — do not edit by hand.",
        "// Source of truth: the YAML files in bundles/. Regenerate after editing them.",
        "namespace CourseAssist.Core;",
        "",
        "/// <summary>Every course bundle, compiled into the program itself.</summary>",
        "public static class EmbeddedBundles",
        "{",
        "    /// <summary>File name → YAML text, including catalog.yaml.</summary>",
        "    public static IReadOnlyDictionary<string, string> Files { get; } =",
        "        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)",
        "        {",
    ]
    for path in files:
        name = os.path.basename(path)
        text = open(path, encoding="utf-8").read().replace("\r\n", "\n")
        if '"""' in text:
            print(f"{name}: contains a triple-quote sequence, cannot embed as raw string", file=sys.stderr)
            return 1
        if not text.endswith("\n"):
            text += "\n"
        lines.append(f'            ["{name}"] = """')
        lines.append(text.rstrip("\n"))
        lines.append('""",')
    lines += [
        "        };",
        "",
        "    public static string? CatalogYaml => Files.TryGetValue(\"catalog.yaml\", out var yaml) ? yaml : null;",
        "}",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} with {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
